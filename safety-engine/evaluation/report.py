"""Render evaluation results as Markdown."""
from __future__ import annotations


def _f(x, nd=3):
    if isinstance(x, float):
        return f"{x:.{nd}f}"
    return str(x)


def _pct(x):
    return f"{100 * x:.1f}%"


def write_markdown(r: dict, path: str):
    L = []
    a = L.append
    a("# Evaluation results — Disaster-Aware Safety Engine (M1–M8)\n")
    a(f"> {r['note']} Generated by `python -m evaluation.run_eval` in {r.get('runtime_s', '?')} s. "
      "These figures come from a simulated city and simulated storms with a hidden ground-truth model. They show how each "
      "mechanism behaves relative to the baselines; they are **not** field measurements and must be labelled as simulation "
      "results wherever they are quoted.\n")

    m1 = r["E1_hazard_model"]
    a("## E1 — Hazard model (M1): calibration and skill\n")
    a("Flood = water depth ≥ 0.15 m at the forecast horizon; event-split test storms.\n")
    a("| Model | AUC-PR | ROC-AUC | Brier | ECE | F1 @ 0.5 | base rate |")
    a("|---|---|---|---|---|---|---|")
    if "flood_levels" in m1:
        pass
    names = {"M1_calibrated": "M1 two-stage + isotonic (proposed)", "M1_uncalibrated": "M1 before calibration",
             "B3_city_weather_RF": "B3 city-weather Random Forest (original design)", "physics_only_est_depth": "Physics-only depth estimate"}
    for k, v in m1["flood"].items():
        a(f"| {names.get(k, k)} | {_f(v.get('auc_pr', float('nan')))} | {_f(v.get('roc_auc', float('nan')))} | {_f(v['brier'], 4)} | {_f(v['ece'], 4)} | {_f(v['f1_at_0_5'])} | {_f(v['base_rate'])} |")
    if "flood_levels" in m1:
        a("\nDepth-exceedance heads (one calibrated model per level, used for vehicle-specific checks):\n")
        a("| Level | AUC-PR | Brier | ECE | base rate |")
        a("|---|---|---|---|---|")
        for k, v in m1["flood_levels"].items():
            a(f"| {k} | {_f(v.get('auc_pr', float('nan')))} | {_f(v['brier'], 4)} | {_f(v['ece'], 4)} | {_f(v['base_rate'])} |")
    a("\nLandslide:\n")
    a("| Model | AUC-PR | Brier | ECE |")
    a("|---|---|---|---|")
    for k, v in m1["landslide"].items():
        a(f"| {names.get(k, k)} | {_f(v.get('auc_pr', float('nan')))} | {_f(v['brier'], 4)} | {_f(v['ece'], 4)} |")

    e = r["E2_E3_routing"]
    a("\n## E2 — Route decisions (M2 + M3) against ground truth\n")
    a("Each request: random origin/destination ≥ 4 km apart, k = 3 candidate routes, three vehicle profiles, "
      "departure every 30 min through the storm. A recommendation is *unsafe* if, at the time the vehicle actually reaches "
      "a segment, true water depth, wind or landslide exceeds that vehicle's limit.\n")
    a("| Method | Requests | Unsafe recommendations | Unsafe among recommended | False refusals | Extra time vs fastest truly-safe |")
    a("|---|---|---|---|---|---|")
    labels = {"B0_fastest": "B0 fastest route, no hazard check", "B1_present_tense": "B1 original design: current hazard polygons, any vehicle",
              "M3_time_aware_vehicle_agnostic": "M3 without vehicle profiles", "M3_full": "M3 (proposed)", "M3_full_plus_M4": "M3 + M4 detours (proposed)"}
    for k, v in e["methods"].items():
        a(f"| {labels[k]} | {v['requests']} | {_pct(v['unsafe_recommendation_rate'])} | {_pct(v['unsafe_among_recommended'])} | "
          f"{_pct(v['false_refusal_rate'])} | {v['mean_extra_time_vs_fastest_truly_safe_s'] / 60:.1f} min |")
    a("\nCandidate-level classification (each of the k candidates):\n")
    a("| Method | Safety recall (unsafe candidates rejected) | False-rejection rate (safe candidates rejected) |")
    a("|---|---|---|")
    for k, v in e["candidates"].items():
        a(f"| {labels[k]} | {_pct(v['safety_recall'])} | {_pct(v['false_rejection_rate'])} |")
    g = e["geometry_tests_per_request"]
    a(f"\nEvaluation cost for k = 3 candidates: p50 {e['latency_ms_k3']['p50']:.0f} ms, p95 {e['latency_ms_k3']['p95']:.0f} ms. "
      f"Exact geometry tests per request: {g['indexed_mean']:.0f} with the spatio-temporal index vs about {g['brute_force_mean']:.0f} "
      f"for a brute-force route × slice × time check ({g['reduction_factor']:.0f}× fewer).\n")

    if "E2b_operating_points" in r:
        a("\nOperating points (safety vs availability), fewer samples:\n")
        a("| Setting | P_MIN | p_hard | α | M3 unsafe | M3 false refusals | B1 unsafe | B1 false refusals |")
        a("|---|---|---|---|---|---|---|---|")
        for k, v in r["E2b_operating_points"].items():
            a(f"| {k} | {v['p_min']} | {v['p_hard']} | {v['alpha']} | {_pct(v['M3_unsafe'])} | {_pct(v['M3_false_refusal'])} | {_pct(v['B1_unsafe'])} | {_pct(v['B1_false_refusal'])} |")
        a("")
    d = e["M4_detour"]
    a("## E3 — Engine-agnostic detours (M4)\n")
    a(f"Requests where all k candidates were infeasible: {d['requests_with_all_candidates_infeasible']}. "
      f"Detour found: {d['detour_found']}; of these truly safe: {d['detour_found_and_truly_safe']}. "
      f"Latency p50 {d['latency_ms_p50']:.0f} ms, p95 {d['latency_ms_p95']:.0f} ms; mean engine re-queries {d['engine_requeries_mean']:.1f}. "
      "The routing graph was never modified or re-preprocessed.\n")

    t = r["E4_trip_revalidation"]
    a("## E4 — Incremental re-validation of active trips (M5)\n")
    a("| Update type | Active trips (mean) | Trips re-evaluated (mean) | Share | Time (mean) |")
    a("|---|---|---|---|---|")
    mr = t["model_refresh"]
    a(f"| 15-min model refresh during storm | {mr['mean_active']:.0f} | {mr['mean_re_evaluated']:.0f} | {_pct(mr['mean_fraction_re_evaluated'])} | {mr['mean_ms']:.0f} ms |")
    lc = t["local_closure"]
    a(f"| Single road closure (admin) | {lc['mean_active']:.0f} | {lc['mean_re_evaluated']:.1f} | {_pct(lc['mean_re_evaluated'] / max(1, lc['mean_active']))} | {lc['mean_ms']:.0f} ms |")
    nv = t["naive_all_trips"]
    a(f"| Baseline: re-evaluate every trip | {nv['trips']:.0f} | {nv['trips']:.0f} | 100% | {nv['ms']:.0f} ms |\n")

    c = r["E5_anti_herding"]
    a("## E5 — Capacity-aware assignment (anti-herding)\n")
    a("900 cars leaving one neighbourhood for the same destination area in the same hour; segment capacity 150 vehicles/h.\n")
    a("| Setting | Assigned | Peak segment load | Peak load / capacity | Segments over capacity | Mean nominal trip time |")
    a("|---|---|---|---|---|---|")
    for k, v in c.items():
        a(f"| {'no capacity term (γ = 0)' if k.endswith('0.0') else 'capacity-aware (γ = 1.5)'} | {v['assigned']} | {v['peak_segment_load']} | {v['peak_load_factor']:.2f} | {v['segments_over_capacity']} | {v['mean_nominal_duration_s'] / 60:.1f} min |")

    gt = r["E6_verification_gate"]
    a("\n## E6 — Verification gate for the assistant (M6)\n")
    a("A simulated unreliable language model corrupts 50% of safety-critical claims (invented ids, an unsafe route "
      "presented as safe, a 'no safe route' claim when one exists, invented SOP clauses).\n")
    a("| Metric | Value |")
    a("|---|---|")
    a(f"| Questions (English, Hindi, Tamil) | {gt['questions']} |")
    a(f"| Answers containing a corrupted claim on first attempt | {gt['corrupted_answers']} |")
    a(f"| Wrong safety-critical claims shown **without** the gate | {gt['ungated_wrong_released']} |")
    a(f"| Wrong safety-critical claims shown **with** the gate | {gt['gated_wrong_released']} |")
    a(f"| Answers corrected after regeneration | {gt['gated_recovered_after_retry']} |")
    a(f"| Answers refused (template-only fallback) | {gt['gated_refusals']} |")
    a(f"| Route claims blocked when hazard data were stale | {gt['stale_data_route_claims_blocked']} |")
    a(f"| End-to-end answer time p50 / p95 | {gt['gate_ms_p50']:.0f} / {gt['gate_ms_p95']:.0f} ms |")

    o = r["E7_offline"]
    a("\n## E7 — Offline support\n")
    a(f"Offline pack for a {o['pack_radius_km']} km radius and {o['pack_hours']} h: {o['slices']} hazard areas, "
      f"{o['graph_nodes']} road nodes, {o['pack_kb']} KB ({o['pack_gzip_kb']} KB gzipped). "
      f"Compact route codes: {', '.join(map(str, o['route_code_chars']))} characters (fits in one SMS).\n")
    if "E8_point_of_no_return" in r:
        e8 = r["E8_point_of_no_return"]
        dv = e8["deadline_vs_truth"]
        a("\n## E8 — Point-of-no-return (leave-by) warning (M8)\n")
        a("For each recommended route the engine reports how long departure can be delayed before the route is cut off. "
          "The deadline is then checked against the hidden ground truth at the time the vehicle would really pass each segment.\n")
        a("| Metric | Value |")
        a("|---|---|")
        a(f"| Requests (random origin/destination × 3 vehicles × departures through the storm) | {e8['requests']} |")
        a(f"| No safe route to recommend | {e8['no_safe_route']} |")
        a(f"| Recommended route with a cut-off countdown / with no cut-off in the forecast window | {e8['countdown']} / {e8['clear']} |")
        gs = e8["given_safe_now"]
        a(f"| Countdown routes truly unsafe if leaving now (forecast misses, same as E2) | {_pct(e8['unsafe_when_leaving_now'])} |")
        a(f"| Truly unsafe when leaving exactly at the deadline | {_pct(e8['unsafe_when_leaving_exactly_at_deadline'])} |")
        a(f"| Truly unsafe when leaving {e8['grace_min']} min after the deadline | {_pct(e8['unsafe_when_leaving_grace_after_deadline'])} |")
        a(f"| Of the routes truly safe now ({gs['n']}): unsafe at the deadline / {e8['grace_min']} min after it | {_pct(gs['unsafe_at_deadline'])} / {_pct(gs['unsafe_grace_after_deadline'])} |")
        a(f"| \"No cut-off\" but truly unsafe for some start inside the window | {_pct(e8['clear_but_truly_unsafe_inside_window'])} |")
        a(f"| Deadline never later than the true deadline (±5 min), {dv['n']} routes that really were cut off | {_pct(dv['conservative_share'])} |")
        a(f"| Deadline minus true deadline, median / mean (negative = earlier, i.e. conservative) | {dv['median_error_min']:.1f} / {dv['mean_error_min']:.1f} min |")
        a(f"| Cost per route: p50 / p95, mean evaluator runs | {e8['scan_ms_p50']:.0f} / {e8['scan_ms_p95']:.0f} ms, {e8['assessments_mean']:.0f} |")
        a("")
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")
